/** 品牌方块底色：图标是纯白 / 纯色时，放在自己的品牌色块上最像那么回事 */
export const BRAND_TILE = { github: '#24292f', gitee: '#c71d23' };

export function brandIcon(platform, size) {
  const d = PATHS[platform] || PATHS.github;
  const s = Number(size) || 18;
  return (
    '<svg class="brand-ico" viewBox="0 0 24 24" width="' + s + '" height="' + s + '" ' +
    'fill="currentColor" aria-hidden="true" focusable="false"><path d="' + d + '"/></svg>'
  );
}

export function hasBrand(platform) {
  return !!PATHS[platform];
}

const api = { brandIcon: brandIcon, BRAND_TILE: BRAND_TILE, hasBrand: hasBrand };
export default api;

