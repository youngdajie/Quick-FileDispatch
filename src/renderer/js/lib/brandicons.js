/** 品牌方块底色：图标是纯白 / 纯色时，放在自己的品牌色块上最像那么回事 */
export const BRAND_TILE = { github: '#24292f', cnb: '#F76945' };

export function brandIcon(platform, size) {
  const ico = ICONS[platform] || ICONS.github;
  const s = Number(size) || 18;
  return (
    '<svg class="brand-ico" viewBox="' + ico.viewBox + '" width="' + s + '" height="' + s + '" ' +
    'fill="currentColor" aria-hidden="true" focusable="false">' +
    ico.paths.map((d) => '<path d="' + d + '"/>').join('') +
    '</svg>'
  );
}

export function hasBrand(platform) {
  return !!ICONS[platform];
}

const api = { brandIcon: brandIcon, BRAND_TILE: BRAND_TILE, hasBrand: hasBrand };
export default api;

